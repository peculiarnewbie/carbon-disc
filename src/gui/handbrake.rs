#[cfg(test)]
mod tests {
    use super::*;
    use crate::{AudioTrackSettings, EncodeRange, EncodeRequest};

    #[test]
    fn more_presets_form_valid_requests() {
        for preset in &MORE_PRESETS {
            let request = EncodeRequest {
                input: "in.mkv".into(),
                output: "out.mp4".into(),
                source_duration_secs: 10.0,
                source_width: Some(3840),
                source_height: Some(2160),
                range: EncodeRange::ALL,
                audio_tracks: vec![AudioTrackSettings {
                    source_index: 1,
                    encoder: preset.settings.audio_encoder,
                    bitrate_kbps: preset.settings.audio_bitrate_kbps,
                }],
                subtitle_tracks: Vec::new(),
                overwrite: false,
                settings: preset.settings.clone(),
            };
            request
                .validate()
                .unwrap_or_else(|error| panic!("{}: {error}", preset.name));
        }
    }
}
