//! HandBrake's official software presets, converted to Carbon Disc settings.
//! Generated from HandBrake's `preset/preset_builtin.json`; hardware presets
//! and ProRes/DNxHR/FFV1 are omitted because this app's encoder set cannot
//! reproduce them. x265 and SVT-AV1 entries map HandBrake's 10-bit encoders
//! onto this app's 8-bit ones, so quality numbers are approximate.

use crate::model::{
    AudioEncoder, Container, CropMargins, EncodeSettings, EncoderSpeed, SubtitleSelection,
    VideoEncoder,
};

pub struct MorePreset {
    /// HandBrake's preset folder, used as a group header in the picker.
    pub category: &'static str,
    pub name: &'static str,
    pub settings: EncodeSettings,
}

#[allow(clippy::too_many_arguments)] // a compact row per preset in the table
const fn p(
    category: &'static str,
    name: &'static str,
    video_encoder: VideoEncoder,
    quality: u8,
    speed: EncoderSpeed,
    container: Container,
    audio_encoder: AudioEncoder,
    audio_bitrate_kbps: u16,
    dimensions: (Option<u32>, Option<u32>),
) -> MorePreset {
    MorePreset {
        category,
        name,
        settings: EncodeSettings {
            container,
            video_encoder,
            quality,
            speed,
            frame_rate: None,
            subtitle_selection: SubtitleSelection::None,
            subtitle_languages: Vec::new(),
            burn_subtitle: false,
            audio_encoder,
            audio_bitrate_kbps,
            max_width: dimensions.0,
            max_height: dimensions.1,
            crop: CropMargins::ZERO,
        },
    }
}

#[must_use]
pub fn find(name: &str) -> Option<&'static MorePreset> {
    MORE_PRESETS.iter().find(|preset| preset.name == name)
}

